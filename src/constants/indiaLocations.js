/**
 * किसी भी राज्य के जिलों की सूची प्राप्त करने हेतु सुरक्षित हेल्पर
 */
export function getDistrictsForState(stateName) {
  if (!stateName) return STATE_DISTRICTS_MAP["उत्तर प्रदेश (Uttar Pradesh)"];
  
  // Direct match
  if (STATE_DISTRICTS_MAP[stateName]) {
    return STATE_DISTRICTS_MAP[stateName];
  }

  // Substring match
  const key = Object.keys(STATE_DISTRICTS_MAP).find(k => 
    k.toLowerCase().includes(stateName.toLowerCase()) || 
    stateName.toLowerCase().includes(k.split(' ')[0].toLowerCase())
  );

  if (key && STATE_DISTRICTS_MAP[key]) {
    return STATE_DISTRICTS_MAP[key];
  }

  return [
    "मुख्यालय जिला / सदर (District HQ)",
    "अन्य जिला (Other District)"
  ];
}

/**
 * राज्य, जिला व गाँव को मिलाकर मानक जन्म स्थान स्ट्रिंग बनाने का हेल्पर
 */
export function formatBirthplace(state, district, village) {
  const parts = [];
  if (village && village.trim()) parts.push(village.trim());
  if (district && district.trim()) parts.push(district.trim());
  if (state && state.trim()) parts.push(state.trim());
  return parts.join(', ');
}
